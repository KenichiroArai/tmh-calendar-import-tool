import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = join(root, "dist");

mkdirSync(distDir, { recursive: true });
copyFileSync(join(root, "src", "appsscript.json"), join(distDir, "appsscript.json"));
const legacyBundledFile = join(distDir, "Code.js");
if (existsSync(legacyBundledFile)) {
  rmSync(legacyBundledFile);
}

const jsFiles = [];

function collectJsFiles(dirPath) {
  const entries = readdirSync(dirPath);
  for (const entry of entries) {
    const fullPath = join(dirPath, entry);
    const stats = statSync(fullPath);
    if (stats.isDirectory()) {
      collectJsFiles(fullPath);
      continue;
    }

    if (extname(fullPath) === ".js") {
      jsFiles.push(fullPath);
    }
  }
}

collectJsFiles(distDir);

for (const filePath of jsFiles) {
  const source = readFileSync(filePath, "utf8");
  const transformed = source
    // Remove ESM imports (single-line imports generated by tsc).
    .replace(/^import\s+.*?;\r?\n/gm, "")
    // Remove `export` prefix from declarations.
    .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var|type|interface))/gm, "")
    // Remove export lists such as `export { foo, bar };`
    .replace(/^export\s*\{[^}]*\};?\r?\n/gm, "");

  writeFileSync(filePath, transformed, "utf8");
}
